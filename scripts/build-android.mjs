#!/usr/bin/env node

import { execSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");
const androidDir = path.join(rootDir, "android");
const outputDir = path.join(rootDir, "dist-apk");

function getJavaMajorVersion(javaHome) {
  try {
    const javaBin = path.join(javaHome, "bin", process.platform === "win32" ? "java.exe" : "java");
    if (!fs.existsSync(javaBin)) return 0;
    const versionOutput = execSync(`"${javaBin}" -version 2>&1`, { encoding: "utf8" });
    const match = versionOutput.match(/(?:version\s+"|\()(\d+)(?:\.|\-)/);
    if (match) {
      return parseInt(match[1], 10);
    }
  } catch {
    return 0;
  }
  return 0;
}

function getCompatibleJavaHome() {
  const candidatePaths = [
    // 1. Homebrew OpenJDK paths
    "/opt/homebrew/opt/openjdk@17/libexec/openjdk.jdk/Contents/Home",
    "/opt/homebrew/opt/openjdk@21/libexec/openjdk.jdk/Contents/Home",
    "/opt/homebrew/opt/openjdk/libexec/openjdk.jdk/Contents/Home",
    // 2. Android Studio bundled JDK
    "/Applications/Android Studio.app/Contents/jbr/Contents/Home",
    // 3. Environment variables
    process.env.JAVA_HOME_17,
    process.env.JAVA_HOME_21,
    process.env.JAVA_HOME,
    // 4. macOS global JDK directories
    "/Library/Java/JavaVirtualMachines/openjdk-17.jdk/Contents/Home",
    "/Library/Java/JavaVirtualMachines/openjdk-21.jdk/Contents/Home",
  ];

  for (const candidate of candidatePaths) {
    if (candidate && fs.existsSync(candidate)) {
      const version = getJavaMajorVersion(candidate);
      if (version >= 17) {
        return { path: candidate, version };
      }
    }
  }

  // On macOS, try /usr/libexec/java_home only if it actually returns >= 17
  if (process.platform === "darwin") {
    try {
      const detected = execSync("/usr/libexec/java_home -v 17+", {
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      }).trim();
      if (detected && fs.existsSync(detected)) {
        const version = getJavaMajorVersion(detected);
        if (version >= 17) {
          return { path: detected, version };
        }
      }
    } catch {
      // ignore
    }
  }

  return null;
}

function ensureAndroidSdk() {
  const localPropsPath = path.join(androidDir, "local.properties");

  if (fs.existsSync(localPropsPath)) {
    const content = fs.readFileSync(localPropsPath, "utf8");
    if (content.includes("sdk.dir")) {
      return null;
    }
  }

  const homedir = os.homedir();
  const candidates = [
    process.env.ANDROID_HOME,
    process.env.ANDROID_SDK_ROOT,
    path.join(homedir, "Library", "Android", "sdk"), // macOS default
    path.join(homedir, "Android", "Sdk"), // Linux default
    process.env.LOCALAPPDATA ? path.join(process.env.LOCALAPPDATA, "Android", "Sdk") : null, // Windows default
  ].filter(Boolean);

  for (const candidate of candidates) {
    if (fs.existsSync(candidate)) {
      console.log(`📱 Detected Android SDK: ${candidate}`);
      const normalizedPath = candidate.replace(/\\/g, "/");
      fs.writeFileSync(
        localPropsPath,
        `## Automatically generated by FoxTrack build script\nsdk.dir=${normalizedPath}\n`,
        "utf8",
      );
      return candidate;
    }
  }

  return null;
}

function runCommand(command, cwd = rootDir, envOverrides = {}) {
  console.log(`\n> [FoxTrack] Running: ${command}`);
  execSync(command, {
    cwd,
    stdio: "inherit",
    env: { ...process.env, ...envOverrides },
  });
}

function main() {
  const startTime = Date.now();
  console.log("=========================================");
  console.log("🚀 Starting FoxTrack Android Build Pipeline");
  console.log("=========================================");

  try {
    const javaInfo = getCompatibleJavaHome();
    if (javaInfo) {
      console.log(`☕ Detected Compatible JDK ${javaInfo.version}: ${javaInfo.path}`);
    } else {
      console.warn(
        "⚠️  Warning: No JDK 17+ detected. Attempting build with default system Java...",
      );
    }

    const detectedSdk = ensureAndroidSdk();

    // 1. Build Next.js Static Export
    console.log("\n📦 Step 1/3: Building Next.js Web Application...");
    runCommand("pnpm run build");

    // 2. Sync with Capacitor
    console.log("\n⚡ Step 2/3: Syncing Web Assets to Android Project...");
    runCommand("pnpm exec cap sync android");

    // 3. Assemble Android APK via Gradle
    console.log("\n🤖 Step 3/3: Building Android APK with Gradle...");
    const isWindows = process.platform === "win32";
    let gradlewCmd = isWindows ? "gradlew.bat assembleDebug" : "./gradlew assembleDebug";
    const envOverrides = {};

    if (javaInfo) {
      gradlewCmd += ` -Dorg.gradle.java.home="${javaInfo.path}"`;
      envOverrides.JAVA_HOME = javaInfo.path;
      const pathSep = isWindows ? ";" : ":";
      envOverrides.PATH = `${path.join(javaInfo.path, "bin")}${pathSep}${process.env.PATH || ""}`;
    }

    if (detectedSdk) {
      envOverrides.ANDROID_HOME = detectedSdk;
    }

    runCommand(gradlewCmd, androidDir, envOverrides);

    // 4. Copy Output to project dist-apk folder
    const sourceApk = path.join(
      androidDir,
      "app",
      "build",
      "outputs",
      "apk",
      "debug",
      "app-debug.apk",
    );

    if (!fs.existsSync(sourceApk)) {
      throw new Error(`APK file not found at expected location: ${sourceApk}`);
    }

    if (!fs.existsSync(outputDir)) {
      fs.mkdirSync(outputDir, { recursive: true });
    }

    const destinationApk = path.join(outputDir, "foxtrack-debug.apk");
    fs.copyFileSync(sourceApk, destinationApk);

    const stats = fs.statSync(destinationApk);
    const sizeInMB = (stats.size / (1024 * 1024)).toFixed(2);
    const duration = ((Date.now() - startTime) / 1000).toFixed(1);

    console.log("\n=========================================");
    console.log("🎉 Android Build Successful!");
    console.log(`⏱  Duration: ${duration}s`);
    console.log(`📁 Output Directory: dist-apk/`);
    console.log(`📱 APK File: dist-apk/foxtrack-debug.apk (${sizeInMB} MB)`);
    console.log("=========================================\n");
  } catch (error) {
    console.error("\n❌ Android Build Failed:", error.message || error);
    process.exit(1);
  }
}

main();
